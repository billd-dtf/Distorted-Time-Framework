"""
DTF_mitosis_branching.py -- toy test of the "mitosis" big-bang hypothesis.

HYPOTHESIS (as stated; not in the paper): Row 0 is a globally pure state whose entanglement
pattern is ASYMMETRIC (DTF's one brute fact). A sub-structure of that ledger -- the "bubble" --
desyncs; the desync then re-spawns desync inside the bubble (binary fission), generation after
generation. Generation n = tick n.

TOY MODEL (stabiliser / Clifford, exact, no sampling error; hbar = k_B = 1):
  * Row-0 ledger  : a pure graph state on n_out outside qubits + n_b bubble seed qubits.
                    'asym' = irregular edges (the brute fact); 'sym' = translation-symmetric ring.
  * fission       : every bubble cell q spawns a daughter d in |0>, CNOT(q->d). N -> 2N.
  * interaction   : one brickwork layer of 2-cell gates on the bubble line (deterministic
                    CZ+H, or with probability p a random Clifford = the seed-making noise).
  * 'nonlocal'    : control where the interaction pairs RANDOM cells instead of neighbours.
Entropies are in bits; the global state is pure by construction (checked).

WHAT IT TESTS (and what it does not):
  T1  S_bubble|outside (entropy of the whole bubble) is unchanged by fission: all the
      bubble's mixedness is inherited from the Row-0 asymmetry, none is generated by branching.
  T2  entropy of a sub-bubble (a lineage, or half the bubble) vs generation: is S ~ c*n ~ ln N?
  T3  does the asymmetric seed wash out (homogeneity) or persist?
  T4  does random branching leave seeds, and with what spectrum slope?
  T5  does S = ln N need locality? (local vs nonlocal pairing)
NOT TESTED: temperature (no Hamiltonian => the state is infinite-temperature; E = N*hbar*omega
and kT = E are NOT exercised), space, EM, the mapping to n_s. The spectrum slope below is a
toy-model number on a 1-D line, not n_s.
"""
import numpy as np

# ----------------------------------------------------------------------------------------
# GF(2) machinery
# ----------------------------------------------------------------------------------------
def gf2_rank(M):
    M = np.ascontiguousarray(M, dtype=np.uint8)
    m, c = M.shape
    if m == 0 or c == 0:
        return 0
    P = np.packbits(M, axis=1)
    r = 0
    for col in range(c):
        byte, mask = col >> 3, 0x80 >> (col & 7)
        below = (P[r:, byte] & mask) != 0
        if not below.any():
            continue
        piv = r + int(np.argmax(below))
        if piv != r:
            P[[r, piv]] = P[[piv, r]]
        rows = r + 1 + np.nonzero((P[r + 1:, byte] & mask) != 0)[0]
        P[rows] ^= P[r]
        r += 1
        if r == m:
            break
    return r

_SEQ = {0: [], 1: ['h'], 2: ['s'], 3: ['s', 'h'], 4: ['h', 's'], 5: ['h', 's', 'h']}

class Stab:
    """Stabiliser state as binary (X|Z) generator rows. Phases dropped: they do not affect entropy."""
    def __init__(self, X, Z):
        self.X = np.array(X, dtype=np.uint8); self.Z = np.array(Z, dtype=np.uint8)
    @property
    def n(self): return self.X.shape[1]
    def add_zero_qubits(self, k):
        m, n = self.X.shape
        X = np.zeros((m + k, n + k), np.uint8); Z = np.zeros_like(X)
        X[:m, :n] = self.X; Z[:m, :n] = self.Z
        Z[m + np.arange(k), n + np.arange(k)] = 1
        self.X, self.Z = X, Z
        return n + np.arange(k)
    def h(self, i):
        if len(i):
            t = self.X[:, i].copy(); self.X[:, i] = self.Z[:, i]; self.Z[:, i] = t
    def s(self, i):
        if len(i): self.Z[:, i] ^= self.X[:, i]
    def cz(self, a, b):
        if len(a):
            xa, xb = self.X[:, a], self.X[:, b]
            self.Z[:, a] ^= xb; self.Z[:, b] ^= xa
    def cnot(self, c, t):
        if len(c):
            self.X[:, t] ^= self.X[:, c]; self.Z[:, c] ^= self.Z[:, t]
    def c1(self, idx, codes):
        for code, ops in _SEQ.items():
            sel = idx[codes == code]
            for op in ops:
                (self.h if op == 'h' else self.s)(sel)
    def S(self, region):
        r = np.asarray(region)
        G = np.concatenate([self.X[:, r], self.Z[:, r]], axis=1)
        return gf2_rank(G) - len(r)

# ----------------------------------------------------------------------------------------
# Self-test against a dense state vector (guards the whole script)
# ----------------------------------------------------------------------------------------
def _dense_selftest(seed=0, nq=6, ngates=60):
    rng = np.random.default_rng(seed)
    Hm = np.array([[1, 1], [1, -1]]) / np.sqrt(2); Sm = np.diag([1, 1j])
    CZ = np.diag([1, 1, 1, -1]).reshape(2, 2, 2, 2)
    CN = np.eye(4)[[0, 1, 3, 2]].reshape(2, 2, 2, 2)
    def a1(psi, U, q, n):
        psi = psi.reshape([2] * n)
        return np.moveaxis(np.tensordot(U, psi, axes=([1], [q])), 0, q).reshape(-1)
    def a2(psi, U, a, b, n):
        psi = psi.reshape([2] * n)
        return np.moveaxis(np.tensordot(U, psi, axes=([2, 3], [a, b])), [0, 1], [a, b]).reshape(-1)
    def dense_S(psi, n, A):
        t = np.moveaxis(psi.reshape([2] * n), list(A), list(range(len(A))))
        sv = np.linalg.svd(t.reshape(2 ** len(A), -1), compute_uv=False) ** 2
        sv = sv[sv > 1e-12]
        return float(-(sv * np.log2(sv)).sum())
    n = nq - 1
    psi = np.zeros(2 ** n, complex); psi[0] = 1
    st = Stab(np.zeros((n, n)), np.eye(n))
    maxerr = 0.0
    for g in range(ngates):
        if g == ngates // 2:                       # grow both by one |0> qubit mid-run
            psi = np.kron(psi, [1, 0]); n += 1; st.add_zero_qubits(1)
        k = rng.integers(0, 4)
        a, b = rng.choice(n, 2, replace=False)
        ia, ib = np.array([a]), np.array([b])
        if k == 0: psi = a1(psi, Hm, a, n); st.h(ia)
        elif k == 1: psi = a1(psi, Sm, a, n); st.s(ia)
        elif k == 2: psi = a2(psi, CZ, a, b, n); st.cz(ia, ib)
        else: psi = a2(psi, CN, a, b, n); st.cnot(ia, ib)
    for _ in range(40):
        A = rng.choice(n, rng.integers(1, n), replace=False)
        maxerr = max(maxerr, abs(dense_S(psi, n, A) - st.S(A)))
    assert st.S(np.arange(n)) == 0, "global state not pure"
    return maxerr

# ----------------------------------------------------------------------------------------
# Row-0 seed ledger and the branching process
# ----------------------------------------------------------------------------------------
N_OUT, N_B = 4, 4
def seed_state(mode):
    n = N_OUT + N_B; A = np.zeros((n, n), np.uint8)
    O = lambda i: i; B = lambda i: N_OUT + i
    if mode == 'asym':
        edges = [(B(0), B(1)), (B(1), B(2)), (B(2), B(3)), (B(0), O(0)), (B(2), O(1)),
                 (B(2), O(2)), (O(0), O(1))]
    else:
        edges = [(B(i), B((i + 1) % N_B)) for i in range(N_B)] + [(B(i), O(i)) for i in range(N_B)]
    for i, j in edges: A[i, j] = A[j, i] = 1
    return Stab(np.eye(n), A), np.array([B(i) for i in range(N_B)]), np.arange(N_OUT)

def interact(st, a, b, rng, p):
    rand = rng.random(len(a)) < p if p > 0 else np.zeros(len(a), bool)
    da, db = a[~rand], b[~rand]
    st.cz(da, db); st.h(da); st.h(db)
    ra, rb = a[rand], b[rand]
    if len(ra):
        for _ in range(2):
            st.c1(ra, rng.integers(0, 6, len(ra))); st.c1(rb, rng.integers(0, 6, len(rb)))
            if _ == 0: st.cz(ra, rb)

def generation(st, order, gen, rng, p, local=True):
    daughters = st.add_zero_qubits(len(order))
    st.cnot(order, daughters)                                   # FISSION
    new = np.empty(2 * len(order), dtype=int); new[0::2] = order; new[1::2] = daughters
    if local:
        pr = np.arange(1, len(new) - 1, 2)                      # pairs straddling parent/daughter
        a, b = new[pr], new[pr + 1]
    else:
        perm = np.random.default_rng(1000 + gen).permutation(new)
        a, b = perm[0::2], perm[1::2]
    interact(st, a, b, rng, p)                                  # INTERACTION
    return new

def observables(st, order, out_idx, g, w=4):
    L = len(order); per = L // N_B
    bubble = st.S(order)
    lin = [st.S(order[s * per:(s + 1) * per]) for s in range(N_B)]
    half = st.S(order[:L // 2])
    mixed = np.mean([st.S([q]) for q in order])
    win = np.array([st.S(order[i:i + w]) for i in range(0, L, w)], float)
    return dict(g=g, N=L, bubble=bubble, lin=lin, half=half, mixed=mixed, win=win)

def run(mode='asym', p=0.0, gens=8, seed=0, local=True, verbose=False):
    st, order, out_idx = seed_state(mode)
    rng = np.random.default_rng(seed)
    rows = [observables(st, order, out_idx, 0)]
    for g in range(1, gens + 1):
        order = generation(st, order, g, rng, p, local)
        rows.append(observables(st, order, out_idx, g))
    assert st.S(np.arange(st.n)) == 0, "global purity lost"
    return rows

def table(rows, title):
    print(f"\n{title}")
    print(f"{'gen':>3} {'N_cells':>7} {'S_bubble':>8} {'S_half':>7} {'S_lineage(mean±sd)':>20} "
          f"{'mixed%':>7} {'window S (mean±sd)':>20}")
    for r in rows:
        l = np.array(r['lin'], float)
        print(f"{r['g']:3d} {r['N']:7d} {r['bubble']:8.0f} {r['half']:7.0f} "
              f"{l.mean():12.2f} ±{l.std():5.2f} {100*r['mixed']:7.1f} "
              f"{r['win'].mean():12.2f} ±{r['win'].std():5.2f}")

def slope_per_gen(rows, key, g0=2):
    g = np.array([r['g'] for r in rows if r['g'] >= g0], float)
    y = np.array([np.mean(r[key]) if key == 'lin' else r[key] for r in rows if r['g'] >= g0], float)
    return np.polyfit(g, y, 1)[0]

def spectrum_slope(winS_list):
    P = None
    for w in winS_list:
        f = np.abs(np.fft.rfft(w - w.mean())) ** 2
        P = f if P is None else P + f
    k = np.arange(1, len(P)); kk = k[: max(4, len(k) // 4)]
    return np.polyfit(np.log(kk), np.log(P[kk]), 1)[0]

